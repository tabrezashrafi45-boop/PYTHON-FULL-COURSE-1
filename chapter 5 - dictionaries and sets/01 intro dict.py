# "DICTIONARY" IS A DATATYPE WHICH IS SIMILAR TO THE "LIST"
# BUT IT STORES "KEY PAIR VALUES" AND USE "{}" BRACKETS FOR CODING
D = {
"TABREZ": 100, 
"TIGER": 200,
"AZIM": 344
}
print(D , type(D)) # we can see the type of "D" which is dictionary.

# it is mutable just like list 
# it is unordered ( means order can't make changes)
# it is already indexed ( but indexed by its key value ( like " tabrez" = 100 ))
# it can't contain duplicates

