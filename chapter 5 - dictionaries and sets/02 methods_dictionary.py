marks = {
    "tabrez": 100,
    "azimushan":200,
    "ozair":230
}
print(marks.items())

 # ".items()" used for giving all the key pairs in the form tuples or list

print(marks.keys())
 # ".keys()" used for giving all keys of the dictionary

marks.update({"azimushan":70, "aale": 20})

print(marks)
# ".update({ })" is used for updating the dictionary and also can add any new values

print(marks.get("aale"))
# ".get()"  is used to find the other key value from one key value

