# when we add something with func is known its argument

# one argument

def goodDay(name): # (name) in bracket used as argument in this function
    print("goodDay",name)
goodDay("tabrez")

# multiple argument
def goodDay(name,ending): # (name,ending) in bracket used as arguments in this function
    print("goodDay",name)
    print(ending) # separate with another print for change the line
goodDay("tabrez","thanks")

# ARGUMENTS IS used for add some value with func

