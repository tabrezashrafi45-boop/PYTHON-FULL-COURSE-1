l1 = [30, 40, 2 ,11 ,63, 19 ,0]
l1.append(80) # ".append" is used to insert any value at the end of the list
print(l1)

l1.sort() # " sort" is used for arranging the list in ascending order
print(l1)

l1.reverse() # "reverse" is used for reversing the order of the list
print(l1)


l1.insert(3,56) #"insert " is used for inserting any value at any index of list
print(l1)

l1.pop(4) # "pop " is used for removing any index from the list
print(l1)

l1.remove(63) # "remove" used to delete direct the item from the list
print(l1)