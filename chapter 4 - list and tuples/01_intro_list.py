# List is a built-in data structure used to store an ordered, 
# mutable (changeable) collection, of items inside square brackets []. 
# Lists are highly versatile because they can hold duplicate values and
#  multiple data types—such as strings, integers, etc .  

list = ["tabrez " , 5 , 8.90 , "apple"] # it can store any type of datatype

 # list indexing 
print(list[1]) # "5" is on index 1

# list mutablity
list[3] = "grapes" 
print(list[3]) # we can easily change any data from the list

# list slicing 
print(list[1:3])